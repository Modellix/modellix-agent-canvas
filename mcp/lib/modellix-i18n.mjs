export const TRANSLATIONS = Object.freeze({ en: Object.freeze(EN), "zh-CN": Object.freeze(ZH_CN), "ja-JP": Object.freeze(JA_JP) });

export function normalizeLanguage(value) {
  const candidate = String(value || "").trim().toLowerCase();
  if (candidate === "zh" || candidate === "zh-cn" || candidate === "zh-hans") return "zh-CN";
  if (candidate === "ja" || candidate === "ja-jp") return "ja-JP";
  return DEFAULT_LANGUAGE;
}

export function translate(language, key, variables = {}) {
  const normalized = normalizeLanguage(language);
  const template = TRANSLATIONS[normalized]?.[key] ?? TRANSLATIONS[DEFAULT_LANGUAGE]?.[key] ?? key;
  return String(template).replace(/\{([A-Za-z0-9_]+)\}/gu, (_match, name) => String(variables[name] ?? `{${name}}`));
}

export function createTranslator(language) {
  const normalized = normalizeLanguage(language);
  return (key, variables) => translate(normalized, key, variables);
}
